# arithmetic operator in python
num_one = int(input("Enter your first number: "))
num_two = int(input("Enter your second number: "))

# addition
sum = num_one + num_two
print(f"{num_one} + {num_two} = {sum}")

# sub
sub = num_one - num_two
print(f"{num_one} - {num_two} = {sub}")

# multiplication
mult = num_one * num_two
print(f"{num_one} x {num_two} = {mult}")

# division
div = num_one / num_two
print(f"{num_one} / {num_two} = {int(div)}")
