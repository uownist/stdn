# break
# ----------
for i in range(1, 11):
    if i == 4:
        break
    print(i)


print("\n")

# ------------
# continue
# ------------
for i in range(1, 7):
    if i == 5:
        continue
    print(i)

print("\n")

# ------------
# pass
# ------------
for i in range(1, 7):
    if i == 5:
        pass
    print(i)
