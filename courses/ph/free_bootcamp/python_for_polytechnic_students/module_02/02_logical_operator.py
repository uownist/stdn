# ------------------
# logical and operator
# ------------------
print(4 < 10 and 2 > 3)  # ---> false
print(4 < 10 and 12 > 3)  # ---> true

print("\n")

# ==============
# logical OR operator
# ==============
print(4 < 5 or 20 > 100)  # ---> ture
print(4 > 10 or 2 < 1)  # ---> false

print("\n")

# =============
# logical not operator
# =============
print(not 5 > 2)  # ---> False
